class Calculator:
    @staticmethod
    def add(a, b):
        return a+b

    @staticmethod
    def subtract(a,b):
        return a-b

    @staticmethod
    def multiply(a,b):
        return a*b


print(Calculator.add(10,20))
print(Calculator.subtract(50,20))
print(Calculator.multiply(10,20))

    






